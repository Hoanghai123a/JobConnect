import { build } from "esbuild";
import { rmSync, readFileSync } from "node:fs";

const out = "./.qr-logic-bundle.mjs";
await build({ entryPoints: ["src/lib/cccd-qr.ts"], bundle: true, format: "esm", platform: "neutral", mainFields: ["module", "main"], outfile: out, logLevel: "silent" });
const mod = await import("./.qr-logic-bundle.mjs?v=" + Date.now());
const src = readFileSync(out, "utf8");
const num = (name) => Number(new RegExp(name + "\\s*=\\s*([0-9.]+)").exec(src)[1]);
const QUAD = num("QUADRANT_OVERLAP_RATIO");
const REF = num("REFINED_OVERLAP_RATIO");
const slice = (from, to) => src.slice(src.indexOf(from), src.indexOf(to));
const buildQuadrantRegions = new Function("QUADRANT_OVERLAP_RATIO", slice("function buildQuadrantRegions", "function buildRefinedRegions") + "; return buildQuadrantRegions;")(QUAD);
const buildRefinedRegions = new Function("buildQuadrantRegions", "REFINED_OVERLAP_RATIO", slice("function buildRefinedRegions", "function renderScanRegion") + "; return buildRefinedRegions;")(buildQuadrantRegions, REF);
let passed = 0, failed = 0;
const check = (name, condition) => { if (condition) { passed++; console.log("PASS  " + name); } else { failed++; console.log("FAIL  " + name); } };
const inside = (box, region) => box.x >= region.x - 1e-6 && box.y >= region.y - 1e-6 && box.x + box.w <= region.x + region.width + 1e-6 && box.y + box.h <= region.y + region.height + 1e-6;
const W = 1600, H = 1000;
const regions = buildQuadrantRegions(W, H);
const refined = buildRefinedRegions(regions);
check("overlap dung 8%", QUAD === 0.08);
check("chia dung 4 vung lon", regions.length === 4);
check("uu tien vung tren-phai truoc", regions[0].x > 0 && regions[0].y === 0);
check("vung trai rong 54% anh", Math.abs(regions[1].width - W * 0.54) < 1e-6);
check("vung phai bat dau tai 46% anh", Math.abs(regions[0].x - W * 0.46) < 1e-6);
check("vung khong vuot khung anh", regions.every((r) => r.x >= 0 && r.y >= 0 && r.x + r.width <= W + 1e-6 && r.y + r.height <= H + 1e-6));
let covered = true;
for (let px = 0; px <= W; px += 25) for (let py = 0; py <= H; py += 25) if (!regions.some((r) => px >= r.x - 1e-6 && px <= r.x + r.width + 1e-6 && py >= r.y - 1e-6 && py <= r.y + r.height + 1e-6)) covered = false;
check("4 vung phu kin toan anh", covered);
const boxes = [
  { name: "QR sat duong chia doc", box: { x: W / 2 - W * 0.03, y: H * 0.3, w: W * 0.06, h: W * 0.06 } },
  { name: "QR sat duong chia ngang", box: { x: W * 0.2, y: H / 2 - H * 0.03, w: H * 0.06, h: H * 0.06 } },
  { name: "QR ngay tam anh", box: { x: W / 2 - 30, y: H / 2 - 30, w: 60, h: 60 } },
  { name: "QR goc tren-phai", box: { x: W - 200, y: 10, w: 180, h: 180 } },
];
for (const item of boxes) check(item.name + " nam tron trong it nhat 1 vung lon", regions.some((r) => inside(item.box, r)));
check("tang chi tiet tao 16 vung", refined.length === 16);
check("vung chi tiet nam trong khung anh", refined.every((r) => r.x >= -1e-6 && r.y >= -1e-6 && r.x + r.width <= W + 1e-6 && r.y + r.height <= H + 1e-6));
check("vung chi tiet dau tien o goc tren-phai", refined[0].x + refined[0].width > W * 0.95 && refined[0].y < 1e-6);
check("QR nho goc tren-phai nam tron trong vung chi tiet", refined.some((r) => inside({ x: W - 150, y: 20, w: 130, h: 130 }, r)));
const fakeQr = "123456789012|987654321|NGUYEN VAN MAU|01011990|Nam|So 1 Duong Test, Ha Noi|02022020";
const dirty = "\uFEFF1234\u200B56789012|9876\u000054321|NGUYEN VAN MAU|01011990|Nam|So 1 Duong Test, Ha Noi|02022020\r\n";
const clean = mod.parseCccdQrText(fakeQr), normalized = mod.parseCccdQrText(dirty);
check("parse QR gia dung so CCCD", clean?.cccd === "123456789012");
check("parse QR gia dung ngay sinh", clean?.dateOfBirth === "01-01-1990");
check("parse QR gia dung ngay cap", clean?.issuedDate === "02-02-2020");
check("chuan hoa ky tu an", JSON.stringify(normalized) === JSON.stringify(clean));
check("tu choi QR thieu truong", mod.parseCccdQrText("123|456|Ten") === null);
const pngFile = new File([new Uint8Array([137, 80, 78, 71])], "fake.png", { type: "image/png" });
const textFile = new File([new Uint8Array([1, 2, 3])], "fake.txt", { type: "text/plain" });
check("tu choi tep khong phai anh", (await mod.scanCccdQrFromFileDetailed(textFile)).reason === "unsupported_image");
globalThis.createImageBitmap = () => new Promise(() => {});
const controller = new AbortController();
const abortPromise = mod.scanCccdQrFromFileDetailed(pngFile, { signal: controller.signal, timeoutMs: 5000 });
setTimeout(() => controller.abort(), 60);
const abortResult = await abortPromise;
check("AbortSignal tra cancelled", abortResult.status === "failed" && abortResult.reason === "cancelled");
const preResult = await mod.scanCccdQrFromFileDetailed(pngFile, { signal: AbortSignal.abort(), timeoutMs: 5000 });
check("signal abort truoc -> cancelled", preResult.status === "failed" && preResult.reason === "cancelled");
const startedAt = Date.now();
const timeoutResult = await mod.scanCccdQrFromFileDetailed(pngFile, { timeoutMs: 500 });
const elapsed = Date.now() - startedAt;
check("timeout tra dung ly do", timeoutResult.status === "failed" && timeoutResult.reason === "timeout");
check("timeout ton trong moc <2s", elapsed < 2000);
const stages = [];
globalThis.createImageBitmap = () => Promise.reject(new Error("no decode"));
await mod.scanCccdQrFromFileDetailed(pngFile, { timeoutMs: 800, onProgress: (stage) => stages.push(stage.step) });
check("callback bao buoc decoding", stages[0] === "decoding");
check("tien trinh khong lot du lieu QR", stages.every((s) => typeof s === "string" && !s.includes("|")));
console.log("\nTONG KET: " + passed + " pass, " + failed + " fail");
rmSync(out, { force: true });
process.exit(failed === 0 ? 0 : 1);
